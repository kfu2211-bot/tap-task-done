using tts.Data;
using tts.Pages;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Razor;
using Microsoft.AspNetCore.Mvc.RazorPages;
using Microsoft.AspNetCore.Mvc.Rendering;
using Microsoft.AspNetCore.Mvc.ViewFeatures;
using Microsoft.AspNetCore.Mvc.ModelBinding;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Logging.Abstractions;
using Microsoft.AspNetCore.DataProtection;
using System.Security.Claims;

void Check(bool condition, string message) { if (!condition) throw new Exception(message); Console.WriteLine("PASS: " + message); }
var missing = AccountSetup.Create(null, [], null, false);
Check(missing.Completed == 0 && missing.NeedsAction, "New account has three incomplete actionable steps");
Check(!AccountSetup.Create("client", [], "approved", true).Complete, "Default client role does not bypass role agreement");
Check(!AccountSetup.Create("both", ["client"], "approved", true).Complete, "Both role requires both current agreements");
var pending = AccountSetup.Create("freelancer", ["freelancer"], "pending", true);
Check(pending.Completed == 2 && !pending.NeedsAction && pending.Steps[1].Status == "Under review" && pending.Steps[1].Action == "View status", "Pending identity is not verified and does not repeatedly prompt resubmission");
var complete = AccountSetup.Create("both", ["client", "freelancer"], "approved", true);
Check(complete.Complete && !complete.NeedsAction, "Complete setup has no reminder");
Check(AccountSetup.Create("client", ["client"], "resubmit", true).Steps[1].Action == "Review request", "Resubmission routes to the existing identity request");
Check(AccountSetup.Create("client", ["client"], "rejected", true).NeedsAction, "Rejected ID prompts attention");
var unavailable = AccountSetup.Create("client", ["client"], "approved", true, false, false, false);
Check(unavailable.Steps.All(s => s.Status == "Unavailable" && !s.Complete) && !unavailable.NeedsAction, "Unavailable data is not mistaken for an incomplete or verified step");
Check(complete.Steps[2].Status == "Added" && complete.Steps[2].Url.Contains("editPhone=true#contact-details"), "Phone is added, not represented as OTP verified, and opens editor");
if (!args.Contains("--serve")) return;
var builder = WebApplication.CreateBuilder(new WebApplicationOptions { Args = args, ContentRootPath = Directory.GetCurrentDirectory() });
builder.Logging.ClearProviders();
builder.Services.AddDataProtection().UseEphemeralDataProtectionProvider();
builder.Services.AddControllersWithViews().AddApplicationPart(typeof(DashboardModel).Assembly);
builder.Services.AddRazorPages().AddApplicationPart(typeof(DashboardModel).Assembly);
builder.WebHost.UseUrls("http://127.0.0.1:5183");
var app = builder.Build(); app.UseStaticFiles();
app.MapGet("/fixture/{name}", async (HttpContext context, string name) => {
    context.User = new ClaimsPrincipal(new ClaimsIdentity([new Claim(ClaimTypes.NameIdentifier, "999999"), new Claim(ClaimTypes.Name, "Preview User")], "fixture"));
    var options = new DbContextOptionsBuilder<ApplicationDbContext>().UseMySql("Server=127.0.0.1;Database=unused;User ID=unused",new MySqlServerVersion(new Version(8,0,36))).Options;
    using var db = new ApplicationDbContext(options); // Rendering only; never connects.
    var model = new DashboardModel(db, NullLogger<DashboardModel>.Instance) { PageContext = new PageContext { HttpContext = context } };
    typeof(DashboardModel).GetProperty("Setup")!.SetValue(model, name switch { "complete" => complete, "pending" => pending, "unavailable" => unavailable, "resubmit" => AccountSetup.Create("client",["client"],"resubmit",false), _ => missing });
    typeof(DashboardModel).GetProperty("SetupReminderKey")!.SetValue(model, "fixture-setup-"+name);
    var view = context.RequestServices.GetRequiredService<IRazorViewEngine>().GetView(null,"/Pages/Dashboard.cshtml",true);
    if (!view.Success) throw new Exception("Missing compiled dashboard view");
    var route = new Microsoft.AspNetCore.Routing.RouteData(); route.Values["page"] = "/Dashboard";
    var action = new ActionContext(context,route,new Microsoft.AspNetCore.Mvc.Abstractions.ActionDescriptor { RouteValues = new Dictionary<string,string?> {{"page","/Dashboard"}} });
    var data = new ViewDataDictionary<DashboardModel>(context.RequestServices.GetRequiredService<IModelMetadataProvider>(), new ModelStateDictionary()) { Model=model };
    model.PageContext.ViewData=data;
    if(view.View is RazorView rv && rv.RazorPage is Page page) page.PageContext=model.PageContext;
    using var writer = new StringWriter();
    await view.View.RenderAsync(new ViewContext(action,view.View,data,new TempDataDictionary(context,context.RequestServices.GetRequiredService<ITempDataProvider>()),writer,new HtmlHelperOptions()));
    context.Response.ContentType="text/html"; await context.Response.WriteAsync(writer.ToString());
});
await app.RunAsync();
