const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {chromium} = require('C:/Users/Mr_Jh/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async () => {
    const browser = await chromium.launch({headless:true,channel:'msedge'});
    try {
        const page = await browser.newPage({viewport:{width:1440,height:1100}});
        const errors = []; page.on('pageerror', e => errors.push(e.message));
        let calls = 0, fail = false, activityFailed = false;
        await page.route('http://users.test/**', async route => {
            const pathname = new URL(route.request().url()).pathname;
            if (pathname === '/fixture') return route.fulfill({contentType:'text/html',body:fs.readFileSync('obj/users-preview.html','utf8')});
            const file = path.resolve('wwwroot', '.' + pathname);
            if (file.startsWith(path.resolve('wwwroot') + path.sep) && fs.existsSync(file) && fs.statSync(file).isFile())
                return route.fulfill({body:fs.readFileSync(file),contentType:file.endsWith('.js')?'application/javascript':file.endsWith('.css')?'text/css':'image/svg+xml'});
            return route.fulfill({status:204});
        });
        await page.route('**/AdminUsers?**', async route => {
            const url = new URL(route.request().url());
            if (url.searchParams.get('handler') === 'Activity') {
                if (activityFailed) return route.fulfill({status:503,body:'Unavailable'});
                return route.fulfill({contentType:'application/json',body:JSON.stringify([{userId:1,online:true,timeIn:'Nov 22, 2026 8:00 AM',lastActive:'Nov 22, 2026 9:30 AM',timeOut:'—'}])});
            }
            if (url.searchParams.get('handler') !== 'Sessions') return route.continue();
            calls++;
            if (fail) return route.fulfill({status:503,body:'Unavailable'});
            assert.equal(url.searchParams.get('userId'),'1');
            const n = Number(url.searchParams.get('pageNumber'));
            await route.fulfill({contentType:'application/json',body:JSON.stringify({hasNext:n===1,rows:[{timeIn:'Nov 22, 2026 8:00 AM',lastActive:'Nov 22, 2026 9:00 AM',timeOut:'—',status:n===1?'Online':'<script>unsafe</script>'}]})});
        });
        await page.goto('http://users.test/fixture');
        assert.equal(await page.locator('.user-card').count(),2);
        const search = page.locator('#userSearch');
        assert.equal(await search.count(),1);
        const searchBounds = await page.locator('.users-search').boundingBox();
        const countBounds = await page.locator('.users-total').boundingBox();
        assert(searchBounds.x < countBounds.x,'Search starts on the left before account count');
        assert.equal(await page.locator('.user-card').first().locator('.unverified-delete').count(),1,'Eligible unverified account has deletion control');
        assert.equal(await page.locator('.user-card').nth(1).locator('.unverified-delete').count(),0,'Verified/ineligible account has no deletion panel');
        await search.fill('k');
        assert.equal(await page.locator('.user-card:visible').count(),1);
        assert.match(await page.locator('.user-card:visible .user-identity').textContent(),/Karl Paras/);
        assert.equal(await page.locator('.user-card:visible .avatar').count(),1);
        await search.fill('ANNE');
        assert.match(await page.locator('.user-card:visible .user-identity').textContent(),/Anne Reyes/);
        await search.fill('not-a-user');
        assert.equal(await page.locator('#noUserMatches').isVisible(),true);
        await search.fill('');
        assert.equal(await page.locator('.user-card:visible').count(),2);
        assert.equal(await page.locator('.user-card .badge').first().textContent(),'No penalty');
        await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
        await page.waitForFunction(()=>document.querySelector('[data-last-active]').textContent==='Nov 22, 2026 9:30 AM');
        assert.equal(await page.locator('[data-presence]').first().textContent(),'Online');
        activityFailed = true;
        await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
        await page.waitForFunction(()=>document.querySelector('[data-presence]').textContent==='Activity unavailable');
        assert.equal(await page.locator('[data-last-active]').first().textContent(),'Nov 22, 2026 9:30 AM');
        activityFailed = false;
        await page.evaluate(()=>document.dispatchEvent(new Event('visibilitychange')));
        await page.waitForFunction(()=>document.querySelector('[data-presence]').textContent==='Online');
        assert.equal(await page.locator('.session-summary').count(),2);
        assert.equal(calls,0,'History should load only when opened');
        const history = page.locator('.session-history').first();
        await history.locator('summary').click();
        await page.waitForFunction(()=>document.querySelectorAll('.session-entry').length===1);
        assert.equal(calls,1);
        fail = true;
        await history.locator('button').click();
        await page.waitForFunction(()=>document.querySelector('.session-more').textContent.includes('Retry'));
        assert.equal(await history.locator('.session-entry').count(),1,'Error retains existing history');
        fail = false;
        await history.locator('button').click();
        await page.waitForFunction(()=>document.querySelectorAll('.session-entry').length===2);
        assert.equal(await history.locator('script').count(),0,'Session values render as text');
        assert.match(await history.textContent(),/<script>unsafe<\/script>/);
        assert.equal(await history.locator('button').isHidden(),true);
        await history.locator('summary').click(); await history.locator('summary').click();
        assert.equal(calls,3,'Reopening does not duplicate requests');
        await page.locator('.penalty-panel').first().locator('summary').click();
        assert.equal(await page.locator('.penalty-clear-state').first().isVisible(),true);
        await page.screenshot({path:'obj/users-unified-desktop.png',fullPage:true});
        await page.setViewportSize({width:390,height:844});
        assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'No horizontal overflow on mobile');
        await page.screenshot({path:'obj/users-unified-mobile.png',fullPage:true});
        assert.deepEqual(errors,[]);
        await search.fill('Karl');
        const refreshRequest = page.waitForRequest(r=>r.url().includes('/AdminUsers?') && !r.url().includes('handler='));
        await page.locator('.refresh-users').click();
        const refreshUrl = new URL((await refreshRequest).url());
        assert.equal(refreshUrl.searchParams.get('Search'),'Karl');
        assert.equal(refreshUrl.searchParams.get('Embedded'),'false');
        console.log('PASS: separate penalty/presence labels, live activity refresh, unavailable/recovery states, one-character search, refresh GET, session history and mobile layout.');
    } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
