using Microsoft.EntityFrameworkCore;

namespace tts.Data;

public sealed class ApplicationDbContext(DbContextOptions<ApplicationDbContext> options)
    : DbContext(options)
{
    public DbSet<AppUser> Users => Set<AppUser>();
    public DbSet<PasswordResetRequest> PasswordResetRequests => Set<PasswordResetRequest>();
    public DbSet<PasswordResetCode> PasswordResetCodes => Set<PasswordResetCode>();
    public DbSet<EmailVerification> EmailVerifications => Set<EmailVerification>();
    public DbSet<VerifiedEmail> VerifiedEmails => Set<VerifiedEmail>();
    public DbSet<FreelancerProfile> FreelancerProfiles => Set<FreelancerProfile>();
    public DbSet<MarketplaceTask> MarketplaceTasks => Set<MarketplaceTask>();
    public DbSet<MarketplaceOffer> MarketplaceOffers => Set<MarketplaceOffer>();
    public DbSet<MarketplaceReview> MarketplaceReviews => Set<MarketplaceReview>();
    public DbSet<MarketplaceMessage> MarketplaceMessages => Set<MarketplaceMessage>();
    public DbSet<MarketplaceNotification> MarketplaceNotifications => Set<MarketplaceNotification>();
    public DbSet<MarketplaceBooking> MarketplaceBookings => Set<MarketplaceBooking>();
    public DbSet<SafetyReport> SafetyReports => Set<SafetyReport>();
    public DbSet<SafetyReportAction> SafetyReportActions => Set<SafetyReportAction>();
    public DbSet<SafetyReportEvidence> SafetyReportEvidence => Set<SafetyReportEvidence>();
    public DbSet<MarketplaceDispute> MarketplaceDisputes => Set<MarketplaceDispute>();
    public DbSet<IdentityRequest> IdentityRequests => Set<IdentityRequest>();
    public DbSet<IdentityResource> IdentityResources => Set<IdentityResource>();
    public DbSet<AccountRestriction> AccountRestrictions => Set<AccountRestriction>();
    public DbSet<AccountModerationAction> AccountModerationActions => Set<AccountModerationAction>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        var progress = modelBuilder.Entity<TaskProgressEvent>();
        progress.ToTable("task_progress_events");
        progress.HasKey(x => x.Id);
        progress.Property(x => x.Status).HasMaxLength(24);
        progress.Property(x => x.Note).HasMaxLength(1000);
        progress.Property(x => x.Photo).HasColumnType("mediumblob");
        progress.Property(x => x.PhotoType).HasMaxLength(32);
        progress.HasIndex(x => new { x.TaskId, x.Id });
        progress.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId).OnDelete(DeleteBehavior.Restrict);
        progress.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ActorId).OnDelete(DeleteBehavior.Restrict);
        var destination = modelBuilder.Entity<TaskDestination>();
        destination.ToTable("task_destinations");
        destination.HasKey(x => x.TaskId);
        destination.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId).OnDelete(DeleteBehavior.Restrict);
        var location = modelBuilder.Entity<FreelancerLocation>();
        location.ToTable("mobile_location_updates");
        location.HasKey(x => x.Id);
        location.HasIndex(x => new { x.TaskId, x.RecordedAtUtc });
        location.HasIndex(x => new { x.UserId, x.RecordedAtUtc });
        location.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
        location.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId).OnDelete(DeleteBehavior.Restrict);
        var evidence = modelBuilder.Entity<SafetyReportEvidence>();
        evidence.ToTable("safety_report_evidence");
        evidence.HasKey(x => x.Id);
        evidence.Property(x => x.ContentType).HasMaxLength(32);
        evidence.Property(x => x.Data).HasColumnType("mediumblob");
        evidence.HasIndex(x => x.ReportId);
        evidence.HasOne<SafetyReport>().WithMany().HasForeignKey(x => x.ReportId).OnDelete(DeleteBehavior.Restrict);
        var restriction = modelBuilder.Entity<AccountRestriction>();
        restriction.ToTable("admin_account_restrictions");
        restriction.HasKey(x => x.UserId);
        restriction.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        restriction.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UpdatedById);
        var accountAction = modelBuilder.Entity<AccountModerationAction>();
        accountAction.ToTable("admin_account_actions");
        accountAction.HasKey(x => x.Id);
        accountAction.Property(x => x.Action).HasMaxLength(16);
        accountAction.Property(x => x.Reason).HasMaxLength(500);
        accountAction.HasIndex(x => new { x.UserId, x.Id });
        accountAction.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        accountAction.HasOne<AppUser>().WithMany().HasForeignKey(x => x.AdminId);
        var identity = modelBuilder.Entity<IdentityRequest>();
        identity.ToTable("identity_requests");
        identity.HasKey(x => x.Id);
        identity.HasIndex(x => new { x.UserId, x.Id });
        identity.Property(x => x.IdLast4).HasMaxLength(4);
        identity.Property(x => x.Status).HasMaxLength(16);
        identity.Property(x => x.ReviewNote).HasMaxLength(500);
        identity.Property(x => x.GovernmentType).HasMaxLength(32);
        identity.Property(x => x.CertificationType).HasMaxLength(32);
        identity.Property(x => x.SupportingType).HasMaxLength(32);
        identity.Property(x => x.GovernmentId).HasColumnType("mediumblob");
        identity.Property(x => x.Certification).HasColumnType("mediumblob");
        identity.Property(x => x.SupportingDocument).HasColumnType("mediumblob");
        identity.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        identity.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ReviewedById);
        var resource = modelBuilder.Entity<IdentityResource>();
        resource.ToTable("identity_resources");
        resource.HasKey(x => x.Id);
        resource.Property(x => x.Kind).HasMaxLength(16);
        resource.Property(x => x.ContentType).HasMaxLength(32);
        resource.Property(x => x.EncryptedData).HasColumnType("mediumblob");
        resource.HasIndex(x => new { x.IdentityRequestId, x.Kind }).IsUnique();
        resource.HasOne<IdentityRequest>().WithMany().HasForeignKey(x => x.IdentityRequestId).OnDelete(DeleteBehavior.Restrict);
        var user = modelBuilder.Entity<AppUser>();
        user.Property(x => x.ProfilePicture).HasColumnType("mediumblob");
        user.ToTable("tbl_user");
        user.HasKey(x => x.Id);
        user.Property(x => x.Id).HasColumnName("Id").ValueGeneratedOnAdd();
        user.Property(x => x.FirstName).HasColumnName("FirstName").HasMaxLength(45);
        user.Property(x => x.LastName).HasColumnName("LastName").HasMaxLength(45);
        user.Property(x => x.Username).HasColumnName("userName").HasMaxLength(45);
        user.Property(x => x.Role).HasColumnName("role").HasMaxLength(45);
        user.Property(x => x.PasswordHash).HasColumnName("Password").HasColumnType("blob");
        user.Property(x => x.DateOfBirth).HasColumnName("DateOfBirth").HasColumnType("date");
        var reset = modelBuilder.Entity<PasswordResetRequest>();
        reset.ToTable("password_reset_requests");
        reset.HasKey(x => x.TokenHash);
        reset.Property(x => x.TokenHash).HasMaxLength(64).IsUnicode(false);
        reset.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        reset.HasIndex(x => x.UserId);
        var resetCode = modelBuilder.Entity<PasswordResetCode>();
        resetCode.ToTable("password_reset_codes");
        resetCode.HasKey(x => x.ChallengeHash);
        resetCode.Property(x => x.ChallengeHash).HasMaxLength(64).IsUnicode(false);
        resetCode.Property(x => x.CodeHash).HasMaxLength(64).IsUnicode(false);
        resetCode.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        resetCode.HasIndex(x => x.UserId);
        var verification = modelBuilder.Entity<EmailVerification>();
        verification.ToTable("email_verification_requests");
        verification.HasKey(x => x.TokenHash);
        verification.Property(x => x.TokenHash).HasMaxLength(64).IsUnicode(false);
        verification.Property(x => x.Email).HasMaxLength(45);
        verification.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        var verified = modelBuilder.Entity<VerifiedEmail>();
        verified.ToTable("verified_emails");
        verified.HasKey(x => x.UserId);
        verified.Property(x => x.Email).HasMaxLength(45);
        verified.HasOne<AppUser>().WithOne().HasForeignKey<VerifiedEmail>(x => x.UserId);
        var profile = modelBuilder.Entity<FreelancerProfile>();
        profile.ToTable("freelancer_profiles");
        profile.HasKey(x => x.UserId);
        profile.HasOne<AppUser>().WithOne().HasForeignKey<FreelancerProfile>(x => x.UserId);
        profile.Property(x => x.Service).HasMaxLength(60);
        profile.Property(x => x.Location).HasMaxLength(80);
        profile.Property(x => x.WorkRole).HasMaxLength(16);
        profile.Property(x => x.Availability).HasMaxLength(16);
        profile.Property(x => x.AvailableDays).HasMaxLength(40);
        var task = modelBuilder.Entity<MarketplaceTask>();
        task.ToTable("marketplace_tasks");
        task.HasKey(x => x.Id);
        task.Property(x => x.Budget).HasPrecision(12, 2);
        task.Property(x => x.CancellationReason).HasMaxLength(500);
        task.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ClientId);
        var offer = modelBuilder.Entity<MarketplaceOffer>();
        offer.ToTable("marketplace_offers");
        offer.HasKey(x => x.Id);
        offer.Property(x => x.Price).HasPrecision(12, 2);
        offer.Property(x => x.WithdrawalReason).HasMaxLength(500);
        offer.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        offer.HasOne<AppUser>().WithMany().HasForeignKey(x => x.FreelancerId);
        offer.HasIndex(x => new { x.TaskId, x.FreelancerId }).IsUnique();
        var review = modelBuilder.Entity<MarketplaceReview>();
        review.ToTable("marketplace_reviews");
        review.HasKey(x => x.Id);
        review.HasIndex(x => x.TaskId).IsUnique();
        review.Property(x => x.Feedback).HasMaxLength(1000);
        review.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        review.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ClientId);
        review.HasOne<AppUser>().WithMany().HasForeignKey(x => x.FreelancerId);
        var message = modelBuilder.Entity<MarketplaceMessage>();
        message.ToTable("marketplace_messages");
        message.HasKey(x => x.Id);
        message.Property(x => x.Body).HasMaxLength(2000);
        message.HasIndex(x => new { x.TaskId, x.Id });
        message.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        message.HasOne<AppUser>().WithMany().HasForeignKey(x => x.SenderId);
        var notification = modelBuilder.Entity<MarketplaceNotification>();
        notification.ToTable("marketplace_notifications");
        notification.HasKey(x => x.Id);
        notification.Property(x => x.Kind).HasMaxLength(30);
        notification.Property(x => x.Message).HasMaxLength(255);
        notification.HasIndex(x => new { x.UserId, x.IsRead, x.Id });
        notification.HasOne<AppUser>().WithMany().HasForeignKey(x => x.UserId);
        notification.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        var booking = modelBuilder.Entity<MarketplaceBooking>();
        booking.ToTable("marketplace_bookings");
        booking.HasKey(x => x.Id);
        booking.Property(x => x.Status).HasMaxLength(24);
        booking.HasIndex(x => new { x.TaskId, x.FreelancerId }).IsUnique();
        booking.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        booking.HasOne<AppUser>().WithMany().HasForeignKey(x => x.FreelancerId);
        var report = modelBuilder.Entity<SafetyReport>();
        report.ToTable("safety_reports");
        report.HasKey(x => x.Id);
        report.Property(x => x.Target).HasMaxLength(80);
        report.Property(x => x.Reason).HasMaxLength(80);
        report.Property(x => x.Description).HasMaxLength(1000);
        report.Property(x => x.Status).HasMaxLength(24);
        report.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ReporterId);
        report.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        report.HasIndex(x => new { x.ReporterId, x.Id });
        var action = modelBuilder.Entity<SafetyReportAction>();
        action.ToTable("safety_report_actions");
        action.HasKey(x => x.Id);
        action.Property(x => x.Status).HasMaxLength(24);
        action.Property(x => x.Note).HasMaxLength(1000);
        action.HasOne<SafetyReport>().WithMany().HasForeignKey(x => x.ReportId);
        action.HasOne<AppUser>().WithMany().HasForeignKey(x => x.AdminId);
        var dispute = modelBuilder.Entity<MarketplaceDispute>();
        dispute.ToTable("marketplace_disputes");
        dispute.HasKey(x => x.Id);
        dispute.Property(x => x.Reason).HasMaxLength(1000);
        dispute.Property(x => x.PreviousTaskStatus).HasMaxLength(24);
        dispute.Property(x => x.Status).HasMaxLength(24);
        dispute.Property(x => x.Resolution).HasMaxLength(1000);
        dispute.HasOne<MarketplaceTask>().WithMany().HasForeignKey(x => x.TaskId);
        dispute.HasOne<AppUser>().WithMany().HasForeignKey(x => x.OpenedById);
        dispute.HasOne<AppUser>().WithMany().HasForeignKey(x => x.ClosedById);
        dispute.HasIndex(x => new { x.TaskId, x.Id });
    }
}
